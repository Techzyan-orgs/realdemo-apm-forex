import type { Metadata } from "next";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { LegalPage } from "@/components/legal/LegalPage";
import { currencyMeta } from "@/data/currencies";

export const metadata: Metadata = { title: "Image credits", alternates: { canonical: "/credits" } };

type Credit = {
  type?: string;
  title?: string;
  source?: string;
  author?: string;
  licence?: string;
  note?: string;
  theme?: string;
  file?: string;
};

async function readCredits(rel: string): Promise<unknown> {
  try {
    return JSON.parse(await readFile(path.join(process.cwd(), "public", rel), "utf8"));
  } catch {
    return null;
  }
}

/** Attribution for third-party images (required by CC BY / BY-SA licences). Generated by assets:fetch. */
export default async function CreditsPage() {
  const currencies = ((await readCredits("currencies/CREDITS.json")) ?? {}) as Record<
    string,
    Credit
  >;
  const banners = ((await readCredits("banners/CREDITS.json")) ?? []) as Credit[];
  const rows = Object.entries(currencies).filter(
    ([, c]) => c.type === "photo" || c.type === "stock-photo",
  );
  return (
    <LegalPage title="Image credits" updated="Generated by assets:fetch">
      <p>
        Banknote and banner images are third-party photographs used under the licences listed below,
        shown at low resolution for illustration.
      </p>
      <h2>Banknotes</h2>
      <ul>
        {rows.map(([code, c]) => (
          <li key={code}>
            <strong>
              {code} – {currencyMeta(code)?.name ?? code}
            </strong>
            : {c.author && !/unknown|see source page/i.test(c.author) ? `${c.author}, ` : ""}
            {c.source ? (
              <a href={c.source} target="_blank" rel="noopener noreferrer">
                source
              </a>
            ) : null}
            {c.licence ? ` · ${c.licence}` : ""}
            {c.note ? ` · ${c.note}` : ""}
          </li>
        ))}
      </ul>
      <h2>Hero banners</h2>
      <ul>
        {banners.map((b, i) => (
          <li key={i}>
            {b.theme ?? b.file}:{" "}
            {b.source ? (
              <a href={b.source} target="_blank" rel="noopener noreferrer">
                source
              </a>
            ) : null}
            {b.licence ? ` · ${b.licence}` : ""}
          </li>
        ))}
      </ul>
    </LegalPage>
  );
}
